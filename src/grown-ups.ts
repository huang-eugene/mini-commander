export const GROWN_UP_GUIDE = `
FOR GROWN-UPS
=============

Your job is not to teach. It is to be a fellow explorer who happens to be
slightly taller.

The three things that matter most
---------------------------------

1. Never say "no, that's wrong".
   Say: "Interesting. Let's see what the computer says."
   The computer is the authority here, not you. That is the whole lesson.

2. Say "I don't know" sometimes. Out loud.
   Then say: "How could we find out?"
   Technical skill is mostly investigation. Watching you not know something
   and find out anyway teaches more than watching you know things.

3. Stop while they still want more.
   A session is 5 to 15 minutes. Ending on "can we do another one?" is a
   win. Ending on a tired child is not, and it costs you tomorrow.

What not to do
--------------

- Don't take the keyboard. Ever. Even when it is slow. Especially then.
- Don't type it for them, and don't spell it out unless they ask.
- Don't correct typos before the computer does. The error message is the
  teaching material, and it is better at this than you are.
- Don't explain what just happened unless they ask. Doing beats explaining.
- Don't skip the "what do you think will happen?" question. Guessing wrong
  is worth more than being told right, and it is the habit we are building.

When they get stuck
-------------------

CHIP has five levels of clue, and the child gets them by typing "hint".
Each one is a bit stronger, ending with the actual answer. Let them ask.
If you jump in first, the hints never get used and they learn that being
stuck means waiting for an adult.

If they are stuck and not asking, try: "What have we not tried yet?"

When they go off exploring
--------------------------

Let them. If they abandon the mission to build fourteen rooms called
"poo", the mission will still be there afterwards and something better is
happening. Curiosity beats the curriculum every time.

The strongest sign this is working is the child saying:
"Can I try something?"

Safety
------

Everything happens inside {{HOME}}.

Nothing outside that folder can be read, written or reached from inside
the game. There is no sudo, no chmod, no kill, and no real delete — "rm"
moves things to a recycling bin and "undo" brings them back. The game
opens no network connections at all; the networking missions run on a
pretend network that lives inside the game.

If you want belt-and-braces isolation you can run it under a separate
computer account, but you do not need to.

Practical things
----------------

- Make the terminal font bigger before you start. Much bigger than you
  think. This is the single easiest thing you can do for a new reader.
- On Windows, use Windows Terminal rather than the old black console
  window if you have it.
- "mini-commander journal" shows you what happened in past sessions and
  what is worth going over again.
- The world persists. Things they build stay built. That matters to them
  more than you would expect, so try not to reset it.
- If typing is the bottleneck, remind them about the Tab key. It finishes
  names for them.

Reading the journal
-------------------

After each session a few lines are added to a journal for you. It says
what was played, whether clues were needed, and which ideas look shaky.
It is not a report card and the child never sees a score, because the
moment this has marks in it, it stops being a game.
`;
